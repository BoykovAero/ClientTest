# Короткие слова опознаём целиком: иначе «мат» находится в «материале»,
# а «тур» — в «турнире» и «культуре».
WHOLE_WORD = frozenset(
    {"мат", "рус", "дз", "тур", "бот", "зал", "курс", "пара", "книга", "книги"}
)

# А эти ищем где угодно, хоть посреди слова: сокращения пишутся слитно с
# чем придётся — «2чфиз2зад», «1чпробфиз».
ANYWHERE = frozenset({"физ"})


def _pattern(word: str) -> re.Pattern:
    if word in ANYWHERE:
        return re.compile(re.escape(word))
    if word in WHOLE_WORD:
        return re.compile(rf"\b{re.escape(word)}\b")
    return re.compile(rf"\b{re.escape(word)}")


PATTERNS: tuple[tuple[str, tuple[re.Pattern, ...]], ...] = tuple(
    (category, tuple(_pattern(word) for word in words)) for category, words in KEYWORDS
)


def detect(text: str) -> str:
    """Направление по тексту дела. Пустая строка — не опознано.

    Считаем совпадения по каждому направлению и берём то, где их больше:
    «сколково доделать тгбот» — дважды Работа, и спорить не о чем. При
    равенстве выигрывает то, что выше в списке.
    """
    haystack = (text or "").casefold().replace("ё", "е")

    best = ""
    best_hits = 0
    for category, patterns in PATTERNS:
        hits = sum(1 for pattern in patterns if pattern.search(haystack))
        if hits > best_hits:
            best, best_hits = category, hits
    return best


def normalise(value: str) -> str:
    """Приводит ответ модели к известному направлению. Иначе пустая строка."""
    cleaned = (value or "").strip().casefold().replace("ё", "е")
    for category in CATEGORIES:
        if cleaned == category.casefold().replace("ё", "е"):
            return category
    return ""
